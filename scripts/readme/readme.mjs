// Assembles README.md from the facts in facts.mjs, the panels in assets/readme/ and the prose in body.md.
// Edit body.md (and the intro below) for wording; never edit README.md by hand.
//
//   node scripts/readme/readme.mjs           write README.md, then verify it
//   node scripts/readme/readme.mjs --check   verify README.md on disk matches what would be generated
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, readFacts } from './facts.mjs';
import { footprintCells, heroDescription } from './panels.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const MARKER = '<!-- generated by scripts/readme/build.mjs. do not edit by hand. -->';
const README = path.join(ROOT, 'README.md');

// Prose wording for each keep reason in background.js keepReason(). facts.mjs already fails if the code and
// the art disagree; this fails if the prose list would.
const PROSE_EXEMPT = {
  active: 'it is the tab on screen in its window',
  pinned: 'it is pinned',
  audible: 'it is playing sound',
  sharing: 'it is using the camera, microphone or screen sharing',
  'never-unload': 'it matches the never-unload list',
};

// Sections a reader must still find below the art. Checked in order.
const REQUIRED_HEADINGS = ['## Install', '## Using it', '## Settings page', '## Limits', '## Development', '## Licence'];

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// A bare <picture>: GitHub's repo page drops the <source> variants when a <picture> sits inside <a>.
function pic(base, alt) {
  return `<picture>
<source media="(max-width: 500px) and (prefers-color-scheme: dark)" srcset="assets/readme/${base}-narrow-dark.svg">
<source media="(max-width: 500px)" srcset="assets/readme/${base}-narrow-light.svg">
<source media="(prefers-color-scheme: dark)" srcset="assets/readme/${base}-dark.svg">
<img alt="${esc(alt)}" src="assets/readme/${base}-light.svg" width="100%">
</picture>`;
}

export function renderReadme() {
  const facts = readFacts();
  const missing = facts.exemptions.filter((k) => !PROSE_EXEMPT[k]);
  if (missing.length) throw new Error(`readme: no prose wording for keep reason(s) ${missing.join(', ')}`);

  const vars = {
    idleMinutes: facts.idleMinutes,
    wakeGapMinutes: facts.wakeGapMinutes,
    checkSentence: facts.checkMinutes === 1 ? 'Once a minute' : `Every ${facts.checkMinutes} minutes`,
    exemptList: facts.exemptions.map((k) => `- ${PROSE_EXEMPT[k]}`).join('\n'),
  };
  let body = fs.readFileSync(path.join(HERE, 'body.md'), 'utf8').replace(/\r\n/g, '\n');
  body = body.replace(/\{\{(\w+)\}\}/g, (m, k) => {
    if (!(k in vars)) throw new Error(`readme: unknown placeholder ${m} in body.md`);
    return String(vars[k]);
  });

  const heroAlt = heroDescription(facts);
  const footAlt = `What the add-on can touch: ${footprintCells(facts).map((cl) => `${cl.n} ${cl.unit} (${cl.note})`).join('; ')}.`;
  const platform = facts.android ? `Firefox ${facts.minFirefox} or later` : `Firefox ${facts.minFirefox} or later on desktop`;

  const intro = [
    MARKER,
    `# ${facts.name}`,
    '',
    pic('hero', heroAlt),
    '',
    `A Firefox add-on that unloads tabs you have not looked at for a while (${facts.idleMinutes} minutes by default). An unloaded tab keeps its place, title and icon in the tab strip, the page's memory is freed and it stops using CPU, and clicking the tab loads the page again. It uses Firefox's own tab-unloading mechanism, run on a timer.`,
    '',
    `Version ${facts.version} · ${platform} · not on addons.mozilla.org: [sign it yourself](#install), or try it now from about:debugging`,
    '',
    '[Install](#install) · [Using it](#using-it) · [Settings](#settings-page) · [Limits](#limits) · [Development](#development) · [Licence](#licence)',
    '',
    pic('footprint', footAlt),
    '',
  ].join('\n');

  return `${intro}\n${body.trimEnd()}\n`;
}

export function verifyReadme(md, expected) {
  let bad = 0;
  const failIf = (cond, msg) => { if (cond) { console.error(`FAIL README.md: ${msg}`); bad++; } };
  const text = md.replace(/\r\n/g, '\n');
  failIf(text.split('\n')[0] !== MARKER, 'first line is not the generated marker');
  if (expected !== undefined) failIf(text !== expected, 'differs from the generated README; run node scripts/readme/build.mjs (or edit body.md, not README.md)');

  const lines = text.split('\n');
  let last = -1;
  for (const h of REQUIRED_HEADINGS) {
    const i = lines.indexOf(h);
    failIf(i < 0, `missing section "${h}"`);
    failIf(i >= 0 && i < last, `section "${h}" is out of order`);
    if (i >= 0) last = i;
  }
  // the art must not push the install story off the first screen
  const install = lines.indexOf('## Install');
  failIf(install > 40, `"## Install" starts on line ${install + 1}; keep it in the first 40 lines`);
  failIf(!text.includes('npm run sign') || !text.includes('Install Add-on From File'), 'install steps are missing');

  // every referenced asset exists; no <picture> wrapped in a link
  for (const m of text.matchAll(/(?:src|srcset)="([^"]+)"/g)) {
    failIf(!/^assets\/readme\//.test(m[1]), `asset ${m[1]} is not in assets/readme/`);
    failIf(!fs.existsSync(path.join(ROOT, m[1])), `missing asset ${m[1]}`);
  }
  failIf(/<a\b[^>]*>\s*<picture/.test(text), 'a <picture> is wrapped in <a>; GitHub repo pages drop its <source> variants');
  failIf(/<img(?![^>]*\balt=")/.test(text), 'an <img> has no alt text');

  // local links resolve; in-page anchors point at real headings
  const slugs = new Set(lines.filter((l) => /^#{1,6} /.test(l)).map((l) => l.replace(/^#+ /, '').toLowerCase().replace(/[^\w\- ]/g, '').replace(/ /g, '-')));
  for (const m of text.matchAll(/\]\(([^)\s]+)\)/g)) {
    const target = m[1];
    if (/^https?:/.test(target)) continue;
    if (target.startsWith('#')) failIf(!slugs.has(target.slice(1)), `anchor ${target} has no heading`);
    else failIf(!fs.existsSync(path.join(ROOT, target.split('#')[0])), `local link ${target} does not exist`);
  }
  failIf(/—/.test(text), 'contains an em dash');
  return bad;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const expected = renderReadme();
  if (process.argv.includes('--check')) {
    process.exitCode = verifyReadme(fs.readFileSync(README, 'utf8'), expected) ? 1 : 0;
  } else {
    fs.writeFileSync(README, expected);
    const bad = verifyReadme(fs.readFileSync(README, 'utf8'), expected);
    if (bad) process.exitCode = 1;
    else console.error(`readme: wrote README.md (${expected.split('\n').length} lines)`);
  }
}
